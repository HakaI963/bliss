package com.altaris.linux.core.terminal

import java.io.File

/**
 * Pure-JVM core of the ble.sh integration: runtime-tree handling, the
 * marker-guarded rc fragment, and the rootfs rc wiring rules.
 *
 * Kept free of Android imports so the exact same logic runs in a plain-JVM
 * harness, and so [ShellIntegration] (Android side) and the staged POSIX
 * `install.sh` (executed as root over the chroot roots) follow one written
 * spec:
 *
 *  - runtime tree: `<rootfs>/usr/local/share/altaris/` = `ble.sh` + `lib/` +
 *    `keymap/` + `altaris-ble-conf.sh` + version stamp. `ble.sh` is **not**
 *    self-contained — a lone copy prints keymap/cmap errors, so the whole
 *    release tree is copied (and [isShareCurrent] rejects partial trees).
 *  - login shells: `/etc/profile.d/altaris-shell.sh` — Alpine and Debian
 *    `/etc/profile` both source every readable fragment in `profile.d`.
 *  - interactive **non-login** bash system rc: `/etc/bash/bashrc` (Alpine and
 *    Void: bash is built with `-DSYS_BASHRC=/etc/bash/bashrc`; Alpine's login
 *    path reaches it through `/etc/profile.d/00-bashrc.sh`), `/etc/bash.bashrc`
 *    (Debian family, also sourced by Debian's `/etc/profile`), `/etc/bashrc`
 *    (Fedora family) — appended only where a distro ships one, created only
 *    for the distro that owns the path.
 *  - user rc: `~/.bashrc` for root and every home user, created when missing —
 *    interactive non-login bash always reads it, including when the distro
 *    ships no system bashrc at all.
 */
object ShellIntegrationTargets {

    /** Generated rc fragments are wrapped in these marker lines. */
    const val MARKER_BEGIN = "# >>> altaris shell integration v1 >>>"
    const val MARKER_END = "# <<< altaris shell integration v1 <<<"

    /**
     * Vendored upstream release (see `assets/shell/`): `ble-0.4.0-devel3`
     * (2023-04-03). Bump on every re-vendor — invalidates the stamps and
     * triggers one re-copy.
     */
    const val BLESH_RELEASE = "0.4.0-devel3+1a5c451c-altaris1"

    /** Version stamp written next to the runtime tree. */
    const val STAMP_NAME = ".altaris-shell-version"

    /** ble.sh config file name (next to the runtime tree). */
    const val CONF_NAME = "altaris-ble-conf.sh"

    /** Guest share dir (absolute path inside a guest rootfs). */
    const val GUEST_SHARE = "/usr/local/share/altaris"

    /** Sanity floor for a healthy vendored `ble.sh` (real file ≈ 950 KB). */
    const val MIN_BLE_SH_BYTES = 300_000L

    /** Stage file name of the rc fragment (cat'ed by the chroot `install.sh`). */
    const val RC_BLOCK_STAGE_NAME = "rc-block.sh"

    /** First line of files the installer creates itself (never added to user files). */
    const val CREATED_HEADER = "# Created by Altaris shell integration (ble.sh)."

    /**
     * ble.sh configuration written next to the runtime tree:
     *  - syntax highlighting on (green resolvable / red wrong),
     *  - history + auto completion on, shared history file,
     *  - face overrides: every command class green, syntax errors red, and
     *    the inline suggestion rendered as subtle gray ghost text (`fg=240`,
     *    same tone as `ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE` for zsh).
     *
     * Face names verified against the vendored copy via `ble-face` (the list
     * in the task brief had `command_external` / `error`, which do not exist
     * in 0.4.0-devel3: PATH-resolved commands use `command_file` and the
     * syntax error face is `syntax_error`).
     */
    val BLE_CONF = """
        |# Altaris ble.sh config — generated by ShellIntegration.kt. Do not edit.
        |# Live syntax coloring: green = resolvable command, red = wrong/unknown.
        |bleopt highlight_syntax=1
        |bleopt complete_auto_history=1
        |bleopt complete_auto_complete=1
        |bleopt history_share=1
        |ble-face -s command_builtin fg=green
        |ble-face -s command_builtin_dot fg=green,bold
        |ble-face -s command_function fg=green
        |ble-face -s command_alias fg=green
        |ble-face -s command_file fg=green
        |ble-face -s syntax_error fg=red
        |ble-face -s auto_complete fg=240
        |""".trimMargin()

    /**
     * Guest rc fragment. Guarded so POSIX sh (dash / busybox ash / Android sh)
     * parses it harmlessly — the `[[ $- == *i* ]]` test is a plain word for
     * those shells, so it is never executed — and only bash sources ble.sh.
     * Never redirects stderr: `source ble.sh 2>/dev/null` switches ble.sh off
     * (verified in a pty). The `BLE_VERSION` guard stops the second copy when
     * one shell reads several wired rc files (e.g. login bash reaching both
     * `/etc/profile.d` and `/etc/bash/bashrc`).
     */
    val GUEST_RC_BLOCK = """
        |$MARKER_BEGIN
        |# ble.sh: live syntax coloring (green valid / red unknown) + inline
        |# history suggestions (Right arrow accepts). Installed by Altaris.
        |if [ -n "${'$'}BASH_VERSION" ] && [ -z "${'$'}{BLE_VERSION-}" ] && [[ ${'$'}- == *i* ]] && [ -r $GUEST_SHARE/ble.sh ]; then
        |    source $GUEST_SHARE/ble.sh
        |    [ -r $GUEST_SHARE/$CONF_NAME ] && . $GUEST_SHARE/$CONF_NAME
        |fi
        |$MARKER_END
        |""".trimMargin()

    /** One rc file to wire, relative to a rootfs root (`etc/bash/bashrc`, `root/.bashrc`, …). */
    data class RcTarget(val relPath: String, val createIfMissing: Boolean)

    // ─────────────────────────────────────────────────────────────────────────
    // Rootfs logic (shared with the chroot install.sh spec)
    // ─────────────────────────────────────────────────────────────────────────

    /** `/home/<user>` dirs (hidden dirs skipped), relative to [root], sorted. */
    fun homeDirs(root: File): List<String> =
        File(root, "home").listFiles()
            ?.filter { it.isDirectory && !it.name.startsWith(".") }
            ?.map { "home/${it.name}" }
            ?.sorted()
            ?: emptyList()

    /**
     * Rc files that must carry the marker block for the rootfs [root]:
     * distro system bashrc (when shipped, or expected for this distro) plus
     * `~/.bashrc` for root and every home user. Deterministic order.
     */
    fun rcTargets(root: File): List<RcTarget> {
        val targets = LinkedHashMap<String, RcTarget>()

        fun add(rel: String, createIfMissing: Boolean) {
            targets.putIfAbsent(rel, RcTarget(rel, createIfMissing))
        }

        // Alpine / Void: bash SYS_BASHRC=/etc/bash/bashrc.
        val alpineBashrc = File(root, "etc/bash/bashrc")
        val hasBash = File(root, "bin/bash").isFile || File(root, "usr/bin/bash").isFile
        if (alpineBashrc.isFile) {
            add("etc/bash/bashrc", createIfMissing = false)
        } else if (File(root, "etc/alpine-release").isFile && hasBash) {
            add("etc/bash/bashrc", createIfMissing = true)
        }

        // Debian family: /etc/bash.bashrc.
        val debian = File(root, "etc/debian_version").isFile
        val debianBashrc = File(root, "etc/bash.bashrc")
        if (debianBashrc.isFile || debian) {
            add("etc/bash.bashrc", createIfMissing = !debianBashrc.isFile)
        }

        // Fedora / RHEL / openSUSE family: /etc/bashrc (only when shipped).
        if (File(root, "etc/bashrc").isFile) {
            add("etc/bashrc", createIfMissing = false)
        }

        if (File(root, "root").isDirectory) {
            add("root/.bashrc", createIfMissing = true)
        }
        for (home in homeDirs(root)) {
            add("$home/.bashrc", createIfMissing = true)
        }
        return targets.values.toList()
    }

    /**
     * True when [file] carries the marker block (detected by the BEGIN line;
     * a partial BEGIN-without-END pair still counts — the block stays
     * functional and Altaris never rewrites or trims user content).
     */
    fun hasMarkerBlock(file: File): Boolean = try {
        file.isFile && file.readText().contains(MARKER_BEGIN)
    } catch (_: Exception) {
        false
    }

    /**
     * Append [block] to [file] unless the marker is already there; returns true
     * when the block is present afterwards. Existing content is never
     * rewritten; when [createIfMissing] the file is created with a minimal
     * [CREATED_HEADER] comment (the block brings its own description comments).
     */
    fun appendMarkerBlock(file: File, block: String, createIfMissing: Boolean): Boolean {
        return try {
            if (!file.isFile) {
                if (!createIfMissing) return false
                file.parentFile?.mkdirs()
                file.writeText(CREATED_HEADER + "\n" + block)
                return true
            }
            val text = file.readText()
            if (text.contains(MARKER_BEGIN)) return true
            val separator = if (text.isEmpty() || text.endsWith("\n")) "" else "\n"
            file.writeText(text + separator + block)
            true
        } catch (_: Exception) {
            false
        }
    }

    /** Write [content] when missing/different; true when the file then holds it. */
    fun writeTextIfDifferent(file: File, content: String): Boolean = try {
        if (file.isFile && file.readText() == content) {
            true
        } else {
            file.parentFile?.mkdirs()
            file.writeText(content)
            true
        }
    } catch (_: Exception) {
        false
    }

    /** True when [share] holds a complete runtime tree of the current release. */
    fun isShareCurrent(share: File): Boolean = try {
        val bleSh = File(share, "ble.sh")
        val stamp = File(share, STAMP_NAME)
        bleSh.isFile && bleSh.length() >= MIN_BLE_SH_BYTES &&
            File(share, "lib/core-syntax.sh").isFile &&
            File(share, "keymap/emacs.sh").isFile &&
            stamp.isFile && stamp.readText().trim() == BLESH_RELEASE
    } catch (_: Exception) {
        false
    }

    /** Write the release stamp for [share]. */
    fun writeStamp(share: File): Boolean =
        writeTextIfDifferent(File(share, STAMP_NAME), "$BLESH_RELEASE\n")

    /**
     * Recursively copy the vendored release from [bleDir] into [share]
     * (`ble.sh` + `lib/` + `keymap/` + conf; stamp and `cache.d` handled by
     * the callers). False when [bleDir] is not a complete release tree.
     */
    fun copyBleTree(bleDir: File, share: File): Boolean {
        val sourceBle = File(bleDir, "ble.sh")
        if (!sourceBle.isFile || sourceBle.length() < MIN_BLE_SH_BYTES) return false
        if (!File(bleDir, "lib").isDirectory || !File(bleDir, "keymap").isDirectory) return false
        return try {
            bleDir.walkTopDown().forEach { file ->
                if (file == bleDir) return@forEach
                val rel = file.relativeTo(bleDir).path
                if (rel == STAMP_NAME || rel == "cache.d" || rel.startsWith("cache.d/")) {
                    return@forEach
                }
                val dest = File(share, rel)
                if (file.isDirectory) {
                    dest.mkdirs()
                } else if (file.isFile) {
                    dest.parentFile?.mkdirs()
                    file.inputStream().use { input ->
                        dest.outputStream().use { output -> input.copyTo(output) }
                    }
                    dest.setReadable(true, false)
                }
            }
            true
        } catch (_: Exception) {
            false
        }
    }

    /**
     * Write `/etc/profile.d/altaris-shell.sh` + every [rcTargets] block into
     * [root] and return [statusLines]. Runtime tree must already be in place
     * ([installIntoRoot] does both). Never throws.
     */
    fun wireRoot(root: File): List<String> {
        val profileD = File(root, "etc/profile.d/altaris-shell.sh")
        if (writeTextIfDifferent(profileD, CREATED_HEADER + "\n" + GUEST_RC_BLOCK)) {
            runCatching { profileD.setExecutable(true, false) }
        }
        for (target in rcTargets(root)) {
            appendMarkerBlock(File(root, target.relPath), GUEST_RC_BLOCK, target.createIfMissing)
        }
        // ble.sh keeps its cache in $HOME/.cache/blesh — prepare root + homes.
        if (File(root, "root").isDirectory) File(root, "root/.cache").mkdirs()
        for (home in homeDirs(root)) File(root, "$home/.cache").mkdirs()
        return statusLines(root)
    }

    /**
     * Full rootfs install (PRoot guests + the JVM harness): stage the runtime
     * tree from [bleDir] when [root]'s copy is stale, then wire every rc
     * target. Returns one status line — never throws.
     */
    fun installIntoRoot(root: File, bleDir: File): List<String> {
        return try {
            val share = File(root, GUEST_SHARE.removePrefix("/"))
            if (!isShareCurrent(share)) {
                if (!copyBleTree(bleDir, share)) {
                    return listOf("error: cannot stage ble.sh tree from ${bleDir.absolutePath}")
                }
                writeStamp(share)
            }
            writeTextIfDifferent(File(share, CONF_NAME), BLE_CONF)
            File(share, "cache.d").mkdirs()
            runCatching {
                share.setReadable(true, false)
                share.setExecutable(true, false)
                File(share, "cache.d").setReadable(true, false)
                File(share, "cache.d").setWritable(true, false)
                File(share, "cache.d").setExecutable(true, false)
            }
            wireRoot(root)
        } catch (e: Exception) {
            listOf("error: ${e.message ?: e.javaClass.simpleName}")
        }
    }

    /**
     * Read-only status for a rootfs, in the report format used by
     * `ShellIntegration.reportLines` — e.g.
     * `ble.sh ok, rc wired (/etc/profile.d/altaris-shell.sh, /etc/bash/bashrc, /root/.bashrc)`.
     */
    fun statusLines(root: File): List<String> {
        val share = File(root, GUEST_SHARE.removePrefix("/"))
        val bleSh = File(share, "ble.sh")
        if (!bleSh.isFile || bleSh.length() < MIN_BLE_SH_BYTES || !File(share, CONF_NAME).isFile) {
            return listOf("ble.sh missing ($GUEST_SHARE/ble.sh)")
        }
        val wired = ArrayList<String>()
        if (hasMarkerBlock(File(root, "etc/profile.d/altaris-shell.sh"))) {
            wired.add("/etc/profile.d/altaris-shell.sh")
        }
        for (target in rcTargets(root)) {
            if (hasMarkerBlock(File(root, target.relPath))) {
                wired.add("/${target.relPath}")
            }
        }
        return if (wired.isEmpty()) {
            listOf("ble.sh ok, rc not wired")
        } else {
            listOf("ble.sh ok, rc wired (${wired.joinToString(", ")})")
        }
    }
}

package com.ivarna.fluxlinux.core.terminal

import android.content.Context
import android.util.Log
import com.ivarna.fluxlinux.BuildConfig
import com.ivarna.fluxlinux.core.install.ProotXfceAssetInstaller
import com.ivarna.fluxlinux.core.root.ChrootPaths
import com.ivarna.fluxlinux.core.utils.RootUtils
import java.io.File

/**
 * Vendored ble.sh integration for every **interactive bash** session.
 *
 * ble.sh is a pure-Bash line editor that gives bash what
 * zsh-autosuggestions / zsh-syntax-highlighting give zsh:
 *  - live syntax coloring (green = resolvable command, red = unknown/half-typed),
 *  - inline history suggestion after the cursor (Right arrow / End accepts),
 *  - ble.sh's completion menu (Tab).
 *
 * The released v0.4 artifact is **not** a single self-contained file: the
 * generated `ble.sh` loads runtime data from `lib/` and `keymap/` next to
 * itself (verified locally — a lone `ble.sh` prints keymap/cmap errors and
 * degrades to the "safe" keymap). The whole release tree is therefore vendored
 * under `assets/shell/` and copied as a directory.
 *
 * Wiring (marker-guarded, idempotent, never clobbers user content):
 *  - host prefix: `<filesDir>/usr/share/bliss/` + a block in the generated
 *    host `~/.bashrc` (see [TermuxHostPaths]).
 *  - PRoot guests: `<rootfs>/usr/local/share/bliss/` +
 *    `<rootfs>/etc/profile.d/bliss-shell.sh` (login shells) +
 *    `<rootfs>/etc/bash.bashrc` (interactive non-login, Debian).
 *  - chroot guests (`/data/local/bliss`, root-only): same files staged under
 *    `<filesDir>/clone-stage/` and copied by one `su` helper pass; skipped
 *    when root is not available (log only, cached per app version).
 *
 * IMPORTANT (verified in a pty): `source ble.sh 2>/dev/null` disables the
 * line editor in v0.4.0-devel3 (stderr must stay a tty while sourcing).
 * Never redirect stderr on the `source` line.
 *
 * [ensureInstalled] is cheap + idempotent (version stamp + stat checks), safe
 * to call on every app start from a background thread.
 */
object ShellIntegration {

    private const val TAG = "ShellIntegration"

    /**
     * Vendored upstream release: `ble-0.4.0-devel3` (2023-04-03), the latest
     * v0.4.x tagged release. `ble.sh` = 950686 bytes, sha256
     * c8413f646d64e0ad2c4ef5d43c97357aa875f502b505c2fd38de760de787c42f.
     * Bump on every re-vendor (invalidates the stamps → one re-copy).
     */
    private const val BLESH_RELEASE = "0.4.0-devel3+1a5c451c"

    /** Assets root of the vendored runtime: `ble.sh` + `lib/` + `keymap/`. */
    private const val ASSET_DIR = "shell"

    /** Generated rc fragments are wrapped in these marker lines. */
    private const val MARKER_BEGIN = "# >>> bliss shell integration v1 >>>"
    private const val MARKER_END = "# <<< bliss shell integration v1 <<<"

    /** Host `$PREFIX` share dir (relative to filesDir). */
    private const val HOST_SHARE_REL = "usr/share/bliss"

    /** Guest share dir (absolute path inside the distro rootfs). */
    private const val GUEST_SHARE = "/usr/local/share/bliss"

    /** Version stamp; matching values make [ensureInstalled] a stat-only pass. */
    private const val STAMP_NAME = ".bliss-shell-version"

    /** ble.sh config file name (next to the runtime tree). */
    private const val CONF_NAME = "bliss-ble-conf.sh"

    /** Sanity floor for a healthy vendored `ble.sh` (real file ≈ 950 KB). */
    private const val MIN_BLE_SH_BYTES = 300_000L

    private const val HOST_RC_BLOCK_NAME = "bashrc-block.sh"

    private const val PREFS = "bliss_shell_integration"
    private const val KEY_CHROOT = "chroot_installed"

    /**
     * ble.sh configuration:
     *  - syntax highlighting on (green resolvable / red wrong),
     *  - history + auto completion on, shared history file,
     *  - face overrides: every command class green, syntax errors red, and
     *    the inline suggestion rendered as subtle gray ghost text (`fg=240`,
     *    same tone as `ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE` for zsh).
     *
     * Face names verified against the vendored copy via `ble-face` (the list
     * in the task brief had `command_external` / `error`, which do not exist
     * in 0.4.0-devel3: PATH-resolved commands use `command_file` and the
     * syntax error face is `syntax_error`).
     */
    private val BLE_CONF = """
        |# Bliss ble.sh config — generated by ShellIntegration.kt. Do not edit.
        |# Live syntax coloring: green = resolvable command, red = wrong/unknown.
        |bleopt highlight_syntax=1
        |bleopt complete_auto_history=1
        |bleopt complete_auto_complete=1
        |bleopt history_share=1
        |ble-face -s command_builtin fg=green
        |ble-face -s command_builtin_dot fg=green,bold
        |ble-face -s command_function fg=green
        |ble-face -s command_alias fg=green
        |ble-face -s command_file fg=green
        |ble-face -s syntax_error fg=red
        |ble-face -s auto_complete fg=240
        |""".trimMargin()

    /**
     * Guest rc fragment. Guarded so POSIX sh (dash / busybox ash) parses it
     * harmlessly and only bash sources ble.sh. Never redirects stderr — that
     * switches ble.sh off (see class doc). The `BLE_VERSION` guard stops the
     * second copy (e.g. Debian `/etc/profile` sources `/etc/bash.bashrc`
     * after `/etc/profile.d`).
     */
    private val GUEST_RC_BLOCK = """
        |$MARKER_BEGIN
        |# ble.sh: live syntax coloring (green valid / red unknown) + inline
        |# history suggestions (Right arrow accepts). Installed by Bliss.
        |if [ -n "${'$'}BASH_VERSION" ] && [ -z "${'$'}{BLE_VERSION-}" ] && [[ ${'$'}- == *i* ]] && [ -r $GUEST_SHARE/ble.sh ]; then
        |    source $GUEST_SHARE/ble.sh
        |    [ -r $GUEST_SHARE/$CONF_NAME ] && . $GUEST_SHARE/$CONF_NAME
        |fi
        |$MARKER_END
        |""".trimMargin()

    /** All chroot rootfs paths shipped by the app. */
    private val CHROOT_ROOTS = listOf(
        ChrootPaths.DEBIAN_CHROOT_PATH,
        ChrootPaths.ALPINE_CHROOT_PATH,
        ChrootPaths.FEDORA_CHROOT_PATH,
        ChrootPaths.VOID_CHROOT_PATH,
        ChrootPaths.OPENSUSE_CHROOT_PATH,
        ChrootPaths.DEEPIN_CHROOT_PATH,
        ChrootPaths.CHIMERA_CHROOT_PATH,
        ChrootPaths.MANJARO_CHROOT_PATH,
        ChrootPaths.UBUNTU_CHROOT_PATH,
        ChrootPaths.KALI_CHROOT_PATH,
        ChrootPaths.PARROT_CHROOT_PATH,
        ChrootPaths.ARCH_CHROOT_PATH
    )

    // ─────────────────────────────────────────────────────────────────────────
    // Public API
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Install / refresh the ble.sh integration everywhere it can go.
     * Cheap when already installed; invokes `su` only for the chroot pass
     * (once per app version). Background thread only (blocking file I/O).
     */
    @Synchronized
    fun ensureInstalled(app: Context) {
        val ctx = app.applicationContext
        try {
            ensureHostPrefix(ctx)
        } catch (e: Exception) {
            Log.w(TAG, "host ble.sh install failed: ${e.message}")
        }
        try {
            ensureProotGuests(ctx)
        } catch (e: Exception) {
            Log.w(TAG, "proot ble.sh install failed: ${e.message}")
        }
        try {
            ensureChrootGuests(ctx)
        } catch (e: Exception) {
            Log.w(TAG, "chroot ble.sh install failed: ${e.message}")
        }
    }

    /** Host prefix share dir: `<filesDir>/usr/share/bliss`. */
    internal fun hostShareDir(filesDir: File): File = File(filesDir, HOST_SHARE_REL)

    // ─────────────────────────────────────────────────────────────────────────
    // Host prefix
    // ─────────────────────────────────────────────────────────────────────────

    private fun ensureHostPrefix(ctx: Context) {
        val share = hostShareDir(ctx.filesDir)
        ensureShareTree(ctx, share)
        // ble.sh prefers $HOME/.cache/blesh when it exists; create it so the
        // cache never has to live inside the (potentially read-only) prefix.
        File(ctx.filesDir, "home/.cache").mkdirs()
        Log.i(TAG, "host ble.sh ready at ${share.absolutePath}")
    }

    // ─────────────────────────────────────────────────────────────────────────
    // PRoot guests
    // ─────────────────────────────────────────────────────────────────────────

    private fun ensureProotGuests(ctx: Context) {
        val prootDistro = File(ctx.filesDir, "usr/var/lib/proot-distro")
        if (!prootDistro.isDirectory) return
        val seen = HashSet<String>()
        val roots = ArrayList<File>()
        File(prootDistro, "containers").listFiles()?.forEach { container ->
            if (!container.isDirectory) return@forEach
            // SSOT builder for the container rootfs path.
            val rootfs = ProotXfceAssetInstaller.prootRootfs(ctx, container.name)
            if (rootfs.isDirectory) addRoot(roots, seen, rootfs)
        }
        // Alternate/legacy layout: installed-rootfs/<name> → rootfs.
        File(prootDistro, "installed-rootfs").listFiles()?.forEach { rootfs ->
            if (rootfs.isDirectory) addRoot(roots, seen, rootfs)
        }
        for (rootfs in roots) {
            try {
                if (!File(rootfs, "etc").isDirectory && !File(rootfs, "usr").isDirectory) continue
                ensureGuestTree(ctx, rootfs)
                Log.i(TAG, "ble.sh installed for proot rootfs ${rootfs.absolutePath}")
            } catch (e: Exception) {
                Log.w(TAG, "proot guest install failed ${rootfs.absolutePath}: ${e.message}")
            }
        }
    }

    private fun addRoot(roots: MutableList<File>, seen: MutableSet<String>, rootfs: File): Boolean {
        val key = try {
            rootfs.canonicalPath
        } catch (_: Exception) {
            rootfs.absolutePath
        }
        return seen.add(key) && roots.add(rootfs)
    }

    /** Copy the runtime + wire profile.d/bash.bashrc into one guest rootfs. */
    private fun ensureGuestTree(ctx: Context, rootfs: File) {
        ensureShareTree(ctx, File(rootfs, GUEST_SHARE.removePrefix("/")))
        // Wired on every call: tiny marker check, repairs a wiped/edited rc.
        writeGuestProfile(rootfs)
        wireGuestBashrc(rootfs)
        ensureGuestCacheDirs(rootfs)
    }

    /**
     * `<rootfs>/etc/profile.d/bliss-shell.sh` — sourced by login shells
     * (Debian/Alpine/Fedora/... `/etc/profile`), mode 755.
     */
    private fun writeGuestProfile(rootfs: File) {
        val file = File(rootfs, "etc/profile.d/bliss-shell.sh")
        val written = writeTextIfDifferent(file, GUEST_RC_BLOCK)
        runCatching { file.setExecutable(true, false) }
        if (written) Log.i(TAG, "wrote ${file.absolutePath}")
    }

    /**
     * Append the same marker block to `/etc/bash.bashrc` when it exists
     * (interactive non-login shells); create it only for Debian-family
     * rootfs (`/etc/debian_version`) when missing.
     */
    private fun wireGuestBashrc(rootfs: File) {
        val bashrc = File(rootfs, "etc/bash.bashrc")
        if (bashrc.isFile) {
            writeMarkerBlock(bashrc, GUEST_RC_BLOCK, createIfMissing = false)
        } else if (File(rootfs, "etc/debian_version").isFile) {
            writeMarkerBlock(bashrc, GUEST_RC_BLOCK, createIfMissing = true)
        }
    }

    /** `.cache` for guest homes so ble.sh uses `$HOME/.cache/blesh`. */
    private fun ensureGuestCacheDirs(rootfs: File) {
        for (home in listOf("home/flux", "root")) {
            val dir = File(rootfs, home)
            if (dir.isDirectory) File(dir, ".cache").mkdirs()
        }
    }

    private fun ensureShareTree(ctx: Context, share: File) {
        val bleSh = File(share, "ble.sh")
        val stale = !isStampCurrent(share) || bleSh.length() < MIN_BLE_SH_BYTES
        if (stale) {
            copyAssetTree(ctx, ASSET_DIR, share)
            if (bleSh.length() < MIN_BLE_SH_BYTES) {
                Log.w(TAG, "vendored ble.sh looks truncated: ${bleSh.length()} bytes")
            }
            writeStamp(share)
        }
        writeTextIfDifferent(File(share, CONF_NAME), BLE_CONF)
        // Fallback cache used when $HOME/.cache/blesh is unavailable: ble.sh
        // writes $_ble_base/cache.d/$UID — it must be writable by the shell.
        File(share, "cache.d").mkdirs()
        runCatching {
            share.setReadable(true, false)
            share.setExecutable(true, false)
            File(share, "cache.d").setReadable(true, false)
            File(share, "cache.d").setWritable(true, false)
            File(share, "cache.d").setExecutable(true, false)
        }
    }

    private fun isStampCurrent(share: File): Boolean = try {
        val stamp = File(share, STAMP_NAME)
        File(share, "ble.sh").isFile && stamp.isFile &&
            stamp.readText().trim() == BLESH_RELEASE
    } catch (_: Exception) {
        false
    }

    private fun writeStamp(share: File) {
        runCatching { File(share, STAMP_NAME).writeText("$BLESH_RELEASE\n") }
    }

    // ─────────────────────────────────────────────────────────────────────────
    // Chroot guests (root-only tree; staged via su)
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Stage the runtime + helper script under `<filesDir>/clone-stage/` and run
     * one `su` pass over every chroot rootfs that exists. Root-unavailable is
     * skipped silently (log only). The `su` pass runs once per app version —
     * the guest side keeps its own marker/stamp afterwards.
     */
    private fun ensureChrootGuests(ctx: Context) {
        val prefs = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val key = "${BuildConfig.VERSION_CODE}"
        if (prefs.getString(KEY_CHROOT, "") == key) return
        if (!RootUtils.isRootAvailable()) {
            Log.i(TAG, "no root — chroot shell integration skipped")
            return
        }
        val stage = File(ctx.filesDir, "clone-stage/bliss-shell")
        try {
            stage.mkdirs()
            copyAssetTree(ctx, ASSET_DIR, File(stage, "blesh"))
            writeTextIfDifferent(File(stage, "blesh/$CONF_NAME"), BLE_CONF)
            writeTextIfDifferent(File(stage, "profile.d.sh"), GUEST_RC_BLOCK)
            writeTextIfDifferent(File(stage, HOST_RC_BLOCK_NAME), "\n" + GUEST_RC_BLOCK)
            writeTextIfDifferent(File(stage, "install.sh"), CHROOT_INSTALL_SCRIPT)
            val install = File(stage, "install.sh")
            val rootArgs = CHROOT_ROOTS.joinToString(" ") { "'$it'" }
            val cmd = "sh '${install.absolutePath}' '${stage.absolutePath}' $rootArgs"
            val result = RootUtils.runRootCommand(cmd)
            if (result.isSuccess) {
                prefs.edit().putString(KEY_CHROOT, key).apply()
                Log.i(TAG, "chroot ble.sh integration applied")
            } else {
                Log.w(TAG, "chroot ble.sh install exit: ${result.error.take(200)}")
            }
        } finally {
            runCatching { stage.deleteRecursively() }
        }
    }

    /** POSIX sh helper executed as root (Android toybox shell) by [ensureChrootGuests]. */
    private val CHROOT_INSTALL_SCRIPT = """
        |#!/bin/sh
        |# Bliss chroot shell integration installer (root). Generated by ShellIntegration.kt.
        |# Usage: sh install.sh <stage-dir> <rootfs> [rootfs...]
        |stage=${'$'}1
        |shift
        |[ -n "${'$'}stage" ] && [ -d "${'$'}stage/blesh" ] || exit 1
        |for root in "${'$'}@"; do
        |  [ -d "${'$'}root/etc" ] || continue
        |  share="${'$'}root$GUEST_SHARE"
        |  mkdir -p "${'$'}share" || continue
        |  cp -rf "${'$'}stage/blesh/." "${'$'}share/" 2>/dev/null || continue
        |  chmod 755 "${'$'}share" 2>/dev/null
        |  chmod 644 "${'$'}share/ble.sh" "${'$'}share/$CONF_NAME" 2>/dev/null
        |  chmod -R a+rX "${'$'}share/lib" "${'$'}share/keymap" 2>/dev/null
        |  mkdir -p "${'$'}share/cache.d" 2>/dev/null
        |  chmod 1777 "${'$'}share/cache.d" 2>/dev/null
        |  mkdir -p "${'$'}root/etc/profile.d" 2>/dev/null
        |  cp -f "${'$'}stage/profile.d.sh" "${'$'}root/etc/profile.d/bliss-shell.sh" 2>/dev/null
        |  chmod 755 "${'$'}root/etc/profile.d/bliss-shell.sh" 2>/dev/null
        |  bashrc="${'$'}root/etc/bash.bashrc"
        |  if [ -f "${'$'}bashrc" ]; then
        |    grep -q 'bliss shell integration v1' "${'$'}bashrc" 2>/dev/null \
        |      || cat "${'$'}stage/$HOST_RC_BLOCK_NAME" >> "${'$'}bashrc" 2>/dev/null
        |  elif [ -f "${'$'}root/etc/debian_version" ]; then
        |    cp -f "${'$'}stage/$HOST_RC_BLOCK_NAME" "${'$'}bashrc" 2>/dev/null
        |  fi
        |  if [ -d "${'$'}root/home/flux" ]; then
        |    mkdir -p "${'$'}root/home/flux/.cache" 2>/dev/null
        |    chown --reference="${'$'}root/home/flux" "${'$'}root/home/flux/.cache" 2>/dev/null \
        |      || chown 1000:1000 "${'$'}root/home/flux/.cache" 2>/dev/null || true
        |  fi
        |  [ -d "${'$'}root/root" ] && mkdir -p "${'$'}root/root/.cache" 2>/dev/null
        |done
        |exit 0
        |""".trimMargin()

    // ─────────────────────────────────────────────────────────────────────────
    // Shared helpers
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Append the marker block to [file] unless the BEGIN marker is already
     * there; returns true when written. Existing content is never touched and
     * a half-present marker pair (BEGIN without END) is left alone.
     */
    private fun writeMarkerBlock(file: File, block: String, createIfMissing: Boolean): Boolean {
        return try {
            val exists = file.isFile
            when {
                !exists && !createIfMissing -> false
                else -> {
                    val text = if (exists) file.readText() else ""
                    if (text.contains(MARKER_BEGIN)) {
                        if (!text.contains(MARKER_END)) {
                            Log.w(TAG, "unterminated bliss marker block in ${file.absolutePath}")
                        }
                        false
                    } else {
                        val separator = if (text.isNotEmpty() && !text.endsWith("\n")) "\n" else ""
                        animateWrite(file, text + separator + block.trimEnd() + "\n")
                    }
                }
            }
        } catch (e: Exception) {
            Log.w(TAG, "marker write failed ${file.absolutePath}: ${e.message}")
            false
        }
    }

    private fun writeTextIfDifferent(file: File, content: String): Boolean = try {
        val have = if (file.isFile) file.readText() else null
        have != content && animateWrite(file, content)
    } catch (e: Exception) {
        Log.w(TAG, "write failed ${file.absolutePath}: ${e.message}")
        false
    }

    private fun animateWrite(file: File, content: String): Boolean = try {
        file.parentFile?.mkdirs()
        file.writeText(content)
        true
    } catch (e: Exception) {
        Log.w(TAG, "write failed ${file.absolutePath}: ${e.message}")
        false
    }

    /** Recursively copy `assets/<assetDir>` into [destDir]. */
    private fun copyAssetTree(ctx: Context, assetDir: String, destDir: File) {
        val children = ctx.assets.list(assetDir) ?: return
        for (name in children) {
            val assetPath = "$assetDir/$name"
            val nested = ctx.assets.list(assetPath)
            if (!nested.isNullOrEmpty()) {
                copyAssetTree(ctx, assetPath, File(destDir, name))
            } else {
                val dest = File(destDir, name)
                dest.parentFile?.mkdirs()
                ctx.assets.open(assetPath).use { input ->
                    dest.outputStream().use { output -> input.copyTo(output) }
                }
            }
        }
    }
}
